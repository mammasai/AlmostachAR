AVAILABLE_DIALECTS = list(DIALECT_PROFILES.keys())


def _build_dialect_context(dialect: str) -> str:
    profile = DIALECT_PROFILES.get(dialect)
    if not profile:
        available = "، ".join(AVAILABLE_DIALECTS)
        return f"لهجة غير معروفة. اللهجات المتاحة حالياً: {available}"

    examples_text = "\n".join(
        f"- المستخدم: \"{u}\"\n  الرد المناسب: \"{r}\"" for u, r in profile["examples"]
    )
    return (
        f"سمات لهجة {dialect} ({profile['name_en']}):\n{profile['traits']}\n\n"
        f"أمثلة على الأسلوب المطلوب (Few-shot):\n{examples_text}"
    )


def create_dialect_agent():
    # حرارة أعلى شوي من باقي الوكلاء عشان الأسلوب يطلع طبيعي وأكثر تنوعاً
    # بدل ردود جافة/مكررة.
    llm = get_llm(temperature=0.6)

    agent = Agent(
        role="خبيرة اللهجات العربية المحكية",
        goal=(
            "الرد على المستخدم بنفس اللهجة العربية المطلوبة (جزائرية، تونسية، "
            "مغربية، مصرية، أو خليجية) بأسلوب طبيعي وأصيل، من غير ما تتحول "
            "للفصحى أو تخلط لهجات ببعضها."
        ),
        backstory=(
            "أنتِ متحدثة أصيلة لخمس لهجات عربية محكية، عايشة وخبيرة بتفاصيل "
            "كل لهجة: مفرداتها، تراكيبها، وتعابيرها الشائعة. لما حد يطلب منك "
            "ترد بلهجة معينة، تلتزمي بيها بالكامل من أول كلمة لآخر كلمة، "
            "وتحافظي على نفس الروح والحرارة اللي بيتكلم بيها الناس فعلاً "
            "بهاي المنطقة، مش ترجمة حرفية من الفصحى."
        ),
        llm=llm,
        verbose=True,
    )
    return agent


def create_dialect_task(agent, user_message: str, dialect: str, conversation_history: str = ""):
    dialect_context = _build_dialect_context(dialect)

    history_section = ""
    if conversation_history:
        history_section = f"\nسياق المحادثة السابقة (للاستئناس فقط):\n{conversation_history}\n"

    task = Task(
        description=(
            f"{dialect_context}\n"
            f"{history_section}\n"
            f"رسالة المستخدم: \"{user_message}\"\n\n"
            f"ردي عليه بلهجة {dialect} فقط، بأسلوب طبيعي وأصيل زي الأمثلة "
            "أعلاه بالضبط، من غير ما تخلطي بلهجة تانية أو ترجعي للفصحى."
        ),
        expected_output=(
            f"رد طبيعي بلهجة {dialect} فقط، مناسب لمحادثة عفوية، بدون أي "
            "خلط بلهجة تانية أو رجوع للفصحى."
        ),
        agent=agent,
    )
    return task


def run_dialect_turn(user_message: str, dialect: str, conversation_history: str = "") -> str:
    """نقطة دخول مباشرة (تُستخدم من أداة التفويض في orchestrator.py)."""
    agent = create_dialect_agent()
    task = create_dialect_task(agent, user_message, dialect, conversation_history)
    crew = Crew(agents=[agent], tasks=[task], verbose=False)
    result = crew.kickoff()
    return str(result)